"""Behavioral checks for the README index; run with Python's standard library."""
from pathlib import Path
import os
import shutil
import subprocess
import tempfile
import unittest


MARKER = '<!-- index is regenerated by scripts/index.sh -->'
SOURCE = Path(__file__).resolve().parents[1] / 'scripts' / 'index.sh'


class IndexTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='til index tests ')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        (self.root / 'scripts').mkdir()
        shutil.copy2(SOURCE, self.root / 'scripts' / 'index.sh')
        self.readme = self.root / 'README.md'
        self.readme.write_text('# Notes\n\nPersonal introduction.\n\n' + MARKER + '\nSTALE INDEX\n', encoding='utf-8')

    def note(self, name, text):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8')

    def run_index(self, expect_success=True, env=None):
        result = subprocess.run(['bash', str(self.root / 'scripts' / 'index.sh')], cwd='/tmp', capture_output=True, text=True, env=env)
        if expect_success:
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(result.stderr, '')
        return result

    def test_preserves_intro_replaces_old_index_and_is_repeatable(self):
        self.note('linux/2026-11-04-example.md', '# Example\n')
        self.run_index()
        first = self.readme.read_text()
        self.run_index()
        self.assertEqual(self.readme.read_text(), first)
        self.assertTrue(first.startswith('# Notes\n\nPersonal introduction.\n\n'))
        self.assertNotIn('STALE INDEX', first)
        self.assertEqual(first.count(MARKER), 1)

    def test_spaces_and_url_punctuation_stay_in_one_working_link(self):
        self.note('linux/2026-11-04-file names (notes)#1?.md', '# Names [and] links\n')
        self.run_index()
        text = self.readme.read_text()
        self.assertIn(r'- [Names \[and\] links](linux/2026-11-04-file%20names%20%28notes%29%231%3F.md)', text)
        self.assertEqual(text.count('\n- ['), 1)

    def test_notes_are_newest_first_within_category(self):
        self.note('linux/2026-10-10-old.md', '# Old\n')
        self.note('linux/2026-11-04-new.md', '# New\n')
        self.run_index()
        text = self.readme.read_text()
        self.assertLess(text.index('[New]'), text.index('[Old]'))

    def test_missing_and_empty_categories_are_skipped(self):
        (self.root / 'docker').mkdir()
        self.run_index()
        self.assertNotIn('###', self.readme.read_text())

    def test_missing_marker_is_added_once(self):
        self.readme.write_text('# Notes\nA short introduction without a final newline')
        self.run_index()
        first = self.readme.read_text()
        self.run_index()
        self.assertEqual(self.readme.read_text(), first)
        self.assertTrue(first.startswith('# Notes\nA short introduction'))
        self.assertEqual(first.count(MARKER), 1)

    def test_missing_readme_fails_without_creating_one(self):
        self.readme.unlink()
        result = self.run_index(expect_success=False)
        self.assertNotEqual(result.returncode, 0)
        self.assertFalse(self.readme.exists())

    def test_failed_render_preserves_readme_and_removes_temporary_file(self):
        self.note('linux/note.md', '# Example\n')
        before = self.readme.read_bytes()
        fake_bin = self.root / 'fake-bin'
        fake_bin.mkdir()
        failing_awk = fake_bin / 'awk'
        failing_awk.write_text('#!/bin/sh\nexit 9\n')
        failing_awk.chmod(0o755)
        env = dict(os.environ, PATH=str(fake_bin) + os.pathsep + os.environ.get('PATH', ''))
        result = self.run_index(expect_success=False, env=env)
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual(self.readme.read_bytes(), before)
        self.assertEqual(list(self.root.glob('.README-index.*')), [])

    def test_no_heading_uses_filename_and_titles_are_never_executed(self):
        self.note('linux/no-heading.md', '\nA note.\n')
        self.note('linux/literal.md', '# `touch HACKED` $(touch HACKED)\n')
        self.run_index()
        text = self.readme.read_text()
        self.assertIn('[no-heading]', text)
        self.assertIn('`touch HACKED` $(touch HACKED)', text)
        self.assertFalse((self.root / 'HACKED').exists())

    def test_crlf_heading_and_percent_in_filename(self):
        self.note('linux/100% ready.md', '# Ready\r\n')
        self.run_index()
        self.assertIn('[Ready](linux/100%25%20ready.md)', self.readme.read_text())

    def test_readme_mode_is_preserved(self):
        self.readme.chmod(0o640)
        self.run_index()
        self.assertEqual(self.readme.stat().st_mode & 0o777, 0o640)


if __name__ == '__main__':
    unittest.main()
