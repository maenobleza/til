#!/usr/bin/env bash
# Rebuild the generated section at the end of README.md, on Bash 3.2+.
set -euo pipefail
export LC_ALL=C
cd -- "$(dirname -- "$0")/.."

if [[ ! -f README.md || -L README.md ]]; then
  printf '%s\n' 'Expected a regular README.md in the repository root.' >&2
  exit 1
fi

marker='<!-- index is regenerated by scripts/index.sh -->'
index_tmp=$(mktemp .README-index.XXXXXX)
trap 'rm -f -- "$index_tmp"' EXIT
# Preserve permissions and render separately. A failed command leaves README intact.
cp -p README.md "$index_tmp"
awk -v marker="$marker" '$0 == marker { exit } { print }' README.md > "$index_tmp"
printf '%s\n' "$marker" >> "$index_tmp"

link_path() {
  local path=$1
  path=${path//\%/%25}
  path=${path// /%20}
  path=${path//$'\t'/%09}
  path=${path//$'\r'/%0D}
  path=${path//$'\n'/%0A}
  path=${path//\#/%23}
  path=${path//\?/%3F}
  path=${path//\(/%28}
  path=${path//\)/%29}
  path=${path//\\/%5C}
  path=${path//</%3C}
  path=${path//>/%3E}
  printf '%s' "$path"
}

shopt -s nullglob
for category in linux docker cloudflare networking ansible; do
  # Quoted arrays preserve spaces and punctuation; glob order is stable in C locale.
  notes=("$category"/*.md)
  heading_written=false
  for ((i=${#notes[@]}-1; i>=0; i--)); do
    file=${notes[i]}
    [[ -f "$file" ]] || continue
    if [[ $heading_written == false ]]; then
      printf '\n### %s\n' "$category" >> "$index_tmp"
      heading_written=true
    fi
    title=$(head -n 1 "$file")
    title=${title%$'\r'}
    title=${title#\# }
    if [[ -z "$title" ]]; then title=${file##*/}; title=${title%.md}; fi
    title=${title//\\/\\\\}
    title=${title//\[/\\[}
    title=${title//\]/\\]}
    printf -- '- [%s](%s)\n' "$title" "$(link_path "$file")" >> "$index_tmp"
  done
done

mv -f -- "$index_tmp" README.md
