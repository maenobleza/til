#!/usr/bin/env bash
# Rebuild the note index at the bottom of README.md
cd "$(dirname "$0")/.."
sed -i '/<!-- index is regenerated/,$d' README.md
echo '<!-- index is regenerated by scripts/index.sh -->' >> README.md
for d in linux docker cloudflare networking ansible; do
  ls "$d"/*.md >/dev/null 2>&1 || continue
  printf '\n### %s\n' "$d" >> README.md
  for f in $(ls "$d"/*.md | sort -r); do
    echo "- [$(head -1 "$f" | sed 's/^# //')]($f)" >> README.md
  done
done
